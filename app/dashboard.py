def generate_dashboard(conn) -> str:
    data = _collect(conn)
    html = TEMPLATE.replace("__DATA_JSON__", json.dumps(data, default=str))
    html = html.replace("RULES_COUNT", str(len(data["rules"])))
    return html


def write_dashboard(conn, out_path: Path = None) -> Path:
    out_path = out_path or (BUNDLE_DIR / "outputs" / "dashboard.html")
    out_path.parent.mkdir(parents=True, exist_ok=True)
    html = generate_dashboard(conn)
    tmp = out_path.with_suffix(".tmp.html")
    tmp.write_text(html, encoding="utf-8")
    tmp.replace(out_path)

    # Mirror to docs/index.html -- GitHub Pages serves a /docs folder on the
    # default branch with zero CI config. Same read-only snapshot, just
    # published where it's reachable without cloning the repo.
    docs_path = BUNDLE_DIR / "docs" / "index.html"
    docs_path.parent.mkdir(parents=True, exist_ok=True)
    docs_tmp = docs_path.with_suffix(".tmp.html")
    docs_tmp.write_text(html, encoding="utf-8")
    docs_tmp.replace(docs_path)

    return out_path
