"""Generates a single self-contained HTML dashboard from the SQLite state.
No CDN, no external fonts, no server, no build step -- opens straight from
disk on a machine with no internet, consistent with the one-command,
clean-machine deploy requirement. All data is embedded as JSON at generation
time; the page is a static snapshot re-generated by `python -m app.cli dashboard`.

Palette and tokens follow the dataviz skill's validated reference palette
(references/palette.md): fixed categorical hue order, reserved status colors,
light/dark both selected (not an automatic flip).

Layout: a left sidebar (persistent navigation, no anchor-scrolling) plus a
right-side detail drawer that opens over the current view instead of
expanding inline -- clicking any ticket anywhere never requires scrolling to
find its detail, which is the whole point of this shape.

Security note: every value that reaches the DOM goes through
document.createTextNode (never innerHTML/insertAdjacentHTML) -- ticket data
includes free-text fields (issue descriptions, quarantine reasons, raw
source records) that must never be interpreted as markup.
"""
import json
from datetime import datetime
from pathlib import Path

from app.narrate import STATE_PLAIN, STEP_PLAIN, plain_ticket_story
from app import pii

BUNDLE_DIR = Path(__file__).resolve().parent.parent


def _collect(conn) -> dict:
    def rows(q, *a):
        return [dict(r) for r in conn.execute(q, a)]

    tickets = rows("SELECT * FROM tickets ORDER BY created_at")
    work_orders = {r["ticket_id"]: r for r in rows("SELECT * FROM work_orders")}
    comms = {r["ticket_id"]: r for r in rows("SELECT * FROM comms")}
    reservations = {r["ticket_id"]: r for r in rows("SELECT * FROM vehicle_reservations")}
    classifications = {r["ticket_id"]: r for r in rows("SELECT * FROM classifications")}
    audit = rows("SELECT * FROM audit_events ORDER BY id")
    audit_by_ticket = {}
    for a in audit:
        audit_by_ticket.setdefault(a["ticket_id"], []).append({
            "step": a["step"], "decision": a["decision"],
            "rule_ids": json.loads(a["rule_ids_json"]), "created_at": a["created_at"], "actor": a["actor"],
        })

    rules_by_id = {r["rule_id"]: r for r in rows("SELECT * FROM rules")}

    # Rejected-candidate detail for blocked tickets -- without this, "no
    # eligible vehicle" reads as a black box. The select_vehicle audit event's
    # data_refs already carries the full per-vehicle rejection reasons; we
    # just need to surface them instead of letting them sit unread in SQLite.
    rejected_by_ticket = {}
    for a in audit:
        if a["step"] == "select_vehicle":
            refs = json.loads(a["data_refs_json"])
            parsed = []
            for ref in refs:
                try:
                    parsed.append(json.loads(ref))
                except (json.JSONDecodeError, TypeError):
                    pass
            if parsed:
                rejected_by_ticket[a["ticket_id"]] = parsed

    ticket_rows = []
    for t in tickets:
        wo = work_orders.get(t["ticket_id"])
        c = comms.get(t["ticket_id"])
        res = reservations.get(t["ticket_id"])
        cls = classifications.get(t["ticket_id"])
        raw = None
        if t["raw_json"]:
            try:
                raw = pii.redact_dict(json.loads(t["raw_json"]))
            except (json.JSONDecodeError, TypeError):
                raw = {"_unparsed": True}
        row = {
            "rejected_candidates": rejected_by_ticket.get(t["ticket_id"], []),
            "ticket_id": t["ticket_id"], "state": t["state"], "client": t["client_canonical"],
            "vehicle": t["reg_canonical"], "replacement": res["reg_canonical"] if res else None,
            "hub": res["hub_used"] if res else None, "severity": (cls["severity"] if cls else t["severity_input"]),
            "origin_hub": t["origin_hub"], "destination": t["destination"], "issue": t["issue"],
            "created_at": t["created_at"], "quarantine_reason": t["quarantine_reason"],
            "work_order_id": wo["work_order_id"] if wo else None,
            "comm_status": c["status"] if c else None,
            "comm_body": c["body"] if c else None,
            "comm_body_deterministic": c["body_deterministic"] if c else None,
            "comm_polished": bool(c["polished"]) if c else False,
            "comm_approved_by": c["approved_by"] if c else None,
            "comm_sent_at": c["sent_at"] if c else None,
            "raw_source_record": raw,
            "first_seen_source": t["first_seen_source"],
            "audit": audit_by_ticket.get(t["ticket_id"], []),
        }
        row["plain_summary"] = plain_ticket_story(row, rules_by_id)
        ticket_rows.append(row)

    state_counts = {}
    for t in ticket_rows:
        state_counts[t["state"]] = state_counts.get(t["state"], 0) + 1

    client_counts = {}
    for t in ticket_rows:
        if t["client"]:
            client_counts[t["client"]] = client_counts.get(t["client"], 0) + 1

    rules = rows("SELECT * FROM rules ORDER BY rule_id")

    state_glossary = [{"state": s, "plain": p} for s, p in STATE_PLAIN.items() if s in state_counts]

    fleet = rows("SELECT COUNT(*) c FROM vehicles")[0]["c"]
    dup_groups = rows("SELECT reg_canonical, COUNT(*) n FROM vehicle_aliases GROUP BY reg_canonical HAVING n > 1")
    conflicts = rows("SELECT COUNT(*) c FROM facts WHERE is_winner=0")[0]["c"]
    docs = rows("SELECT COUNT(*) c FROM documents")[0]["c"]

    kpis = {
        "tickets_total": len(ticket_rows),
        "work_orders": len(work_orders),
        "comms_pending": sum(1 for c in comms.values() if c["status"] == "PENDING"),
        "comms_sent": sum(1 for c in comms.values() if c["status"] == "SENT"),
        "quarantined": state_counts.get("QUARANTINED", 0),
        "blocked": state_counts.get("BLOCKED_NO_ELIGIBLE_VEHICLE", 0),
        "vehicles_resolved": fleet,
        "duplicate_groups_merged": len(dup_groups),
        "fact_conflicts_resolved": conflicts,
        "rules_encoded": len(rules),
        "documents_indexed": docs,
    }

    pii_paths = (list((BUNDLE_DIR / "outputs").glob("*.jsonl")) + [BUNDLE_DIR / "audit" / "audit.jsonl"]
                 + [BUNDLE_DIR / "docs" / "index.html"])
    pii_findings = pii.scan_paths(pii_paths)

    pii_audit_row = conn.execute("SELECT value FROM run_meta WHERE key='pii_redaction_audit'").fetchone()
    pii_redaction_audit = json.loads(pii_audit_row["value"]) if pii_audit_row else []

    recent_activity = []
    for a in rows("SELECT * FROM audit_events ORDER BY id DESC LIMIT 18"):
        recent_activity.append({
            "ticket_id": a["ticket_id"], "step": a["step"], "decision": a["decision"],
            "created_at": a["created_at"], "actor": a["actor"],
        })

    # Fleet: every vehicle, segmented as its own record type -- not just a
    # field inside a ticket. Includes live reservation status (is this truck
    # currently claimed by an in-flight ticket in this run?) and a rollup of
    # its maintenance history, so "why is this truck ineligible" is
    # answerable from the Fleet view alone, not only from a blocked ticket's
    # rejected-candidates list.
    active_reservations = {r["reg_canonical"]: r["ticket_id"] for r in rows(
        "SELECT reg_canonical, ticket_id FROM vehicle_reservations"
    )}
    maint_counts = {}
    maint_last = {}
    for m in rows("SELECT reg_canonical, event_date FROM maintenance_events ORDER BY event_date"):
        maint_counts[m["reg_canonical"]] = maint_counts.get(m["reg_canonical"], 0) + 1
        maint_last[m["reg_canonical"]] = m["event_date"]
    fleet = []
    for v in rows("SELECT * FROM vehicles ORDER BY vehicle_id"):
        fleet.append({
            "vehicle_id": v["vehicle_id"], "reg": v["reg_canonical"], "model": v["model"], "year": v["year"],
            "bs_stage": v["bs_stage"], "engine_heater": v["engine_heater"], "home_hub": v["home_hub"],
            "capacity_tonnes": v["capacity_tonnes"], "status": v["status"],
            "reserved_by": active_reservations.get(v["reg_canonical"]),
            "maintenance_events": maint_counts.get(v["reg_canonical"], 0),
            "last_maintenance": maint_last.get(v["reg_canonical"]),
        })
    fleet_hubs = sorted({v["home_hub"] for v in fleet if v["home_hub"]})

    quarantined_list = [t for t in ticket_rows if t["state"] == "QUARANTINED"]
    blocked_list = [t for t in ticket_rows if t["state"] == "BLOCKED_NO_ELIGIBLE_VEHICLE"]
    pending_list = [t for t in ticket_rows if t["state"] == "COMMS_PENDING"]
    next_action = None
    if blocked_list:
        next_action = {"ticket": blocked_list[0], "reason": "No eligible vehicle was found automatically — needs a manual assignment.", "kind": "blocked"}
    elif quarantined_list:
        next_action = {"ticket": quarantined_list[0], "reason": "This record is missing information the pipeline needs — needs a correction.", "kind": "quarantined"}
    elif pending_list:
        next_action = {"ticket": pending_list[0], "reason": "A client message is drafted and ready — needs approval.", "kind": "pending"}

    return {
        "generated_at": datetime.utcnow().isoformat() + "Z",
        "kpis": kpis,
        "state_counts": state_counts,
        "state_glossary": state_glossary,
        "step_plain": STEP_PLAIN,
        "client_counts": client_counts,
        "tickets": ticket_rows,
        "needs_attention": {
            "quarantined": [t for t in ticket_rows if t["state"] == "QUARANTINED"],
            "blocked": [t for t in ticket_rows if t["state"] == "BLOCKED_NO_ELIGIBLE_VEHICLE"],
            "comms_pending": [t for t in ticket_rows if t["state"] == "COMMS_PENDING"],
        },
        "comms_sent_list": [t for t in ticket_rows if t["state"] == "COMMS_SENT"],
        "rules": rules,
        "pii_clean": len(pii_findings) == 0,
        "pii_findings_count": len(pii_findings),
        "pii_redaction_audit": pii_redaction_audit,
        "pii_redaction_total": sum(a["total"] for a in pii_redaction_audit),
        "recent_activity": recent_activity,
        "next_action": next_action,
        "fleet": fleet,
        "fleet_hubs": fleet_hubs,
    }


